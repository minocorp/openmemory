SET LOCAL lock_timeout = '5s';

CREATE CONSTRAINT TRIGGER page_versions_journal
AFTER INSERT ON page_versions
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION journal_append();

CREATE CONSTRAINT TRIGGER files_upload_journal
AFTER INSERT ON files
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION journal_append();

CREATE CONSTRAINT TRIGGER files_delete_journal
AFTER UPDATE OF deleted_at ON files
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
WHEN (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
EXECUTE FUNCTION journal_append();

CREATE CONSTRAINT TRIGGER purges_journal
AFTER INSERT ON purges
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION journal_append();
